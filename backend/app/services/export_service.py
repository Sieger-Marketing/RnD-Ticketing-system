def to_pdf(report: Report) -> bytes:
    """Landscape A4: these tables are wide, and a wrapped table is unreadable."""
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle", parent=styles["Title"], fontSize=16, alignment=TA_LEFT, spaceAfter=2
    )
    meta_style = ParagraphStyle(
        "ReportMeta", parent=styles["Normal"], fontSize=8.5, textColor=colors.HexColor("#647691")
    )
    section_style = ParagraphStyle(
        "SectionTitle", parent=styles["Heading2"], fontSize=11, spaceBefore=10, spaceAfter=4
    )
    note_style = ParagraphStyle(
        "Note", parent=styles["Normal"], fontSize=7.5, textColor=colors.HexColor("#647691")
    )
    cell_style = ParagraphStyle("Cell", parent=styles["Normal"], fontSize=7.5, leading=9)

    stream = io.BytesIO()
    document = SimpleDocTemplate(
        stream,
        pagesize=landscape(A4),
        leftMargin=14 * mm,
        rightMargin=14 * mm,
        topMargin=12 * mm,
        bottomMargin=12 * mm,
        title=report.title,
    )

    story: list = [
        Paragraph(report.title, title_style),
        Paragraph(report.period_label, meta_style),
        Paragraph(
            f"Generated {report.generated_at.strftime('%d %b %Y, %H:%M')}"
            + (f" by {report.generated_by}" if report.generated_by else ""),
            meta_style,
        ),
        Spacer(1, 8),
    ]

    if report.summary:
        summary_rows = [
            [label, DASH if value is None else str(value)]
            for label, value in report.summary
        ]
        table = Table(summary_rows, colWidths=[70 * mm, 40 * mm], hAlign="LEFT")
        table.setStyle(
            TableStyle(
                [
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#4F5F78")),
                    ("FONTNAME", (1, 0), (1, -1), "Helvetica-Bold"),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("LINEBELOW", (0, 0), (-1, -2), 0.25, colors.HexColor("#ECEEF2")),
                ]
            )
        )
        story.extend([table, Spacer(1, 6)])

    for index, section in enumerate(report.sections):
        if index > 0:
            story.append(PageBreak())
        story.append(Paragraph(section.title, section_style))

        if not section.rows:
            story.append(Paragraph("No rows for this period.", note_style))
            continue

        header = [Paragraph(f"<b>{c}</b>", cell_style) for c in section.columns]
        body = [
            [
                Paragraph(DASH if cell is None else str(cell), cell_style)
                for cell in row
            ]
            for row in section.rows
        ]

        table = Table([header, *body], repeatRows=1, hAlign="LEFT")
        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F45DB")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#D5DAE2")),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F6F7F9")]),
                    ("LEFTPADDING", (0, 0), (-1, -1), 4),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ]
            )
        )
        story.append(table)

        if section.note:
            story.extend([Spacer(1, 3), Paragraph(section.note, note_style)])

    document.build(story)
    return stream.getvalue()


RENDERERS = {
    "csv": (to_csv, "text/csv", "csv"),
    "xlsx": (
        to_xlsx,
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "xlsx",
    ),
    "pdf": (to_pdf, "application/pdf", "pdf"),
}
